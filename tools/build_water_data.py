#!/usr/bin/env python3
"""Builds project/scripts/water_data.gd from docs/gis/water-features-*.json.

The JSON is the reviewed trace of the ditch and pond (see tools/water_overlay.py);
this script flattens it into the constants the carved terrain reads at runtime,
so the game never has to parse the docs folder (Godot's res:// can't reach it).

    python3 tools/build_water_data.py

The full route is also kept in flow order (ROUTE_SEGMENTS) for the water simulation.
Open ditch runs become one flat segment list (ax, az, bx, bz per segment); buried
runs (culverts and the pipe to the pond) are kept separately and are NOT carved.
The pond is its spine of (x, z, half-width) points, less the ground north of its
cut-back north shore. The overflow channel is kept the same way (OUTFLOW_*).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/gis/water-features-340732310005.json"
OUT = ROOT / "project/scripts/water_data.gd"


def flat(rows):
    return ",\n".join("\t" + ", ".join(repr(round(float(v), 3)) for v in row) for row in rows)


def main():
    d = json.loads(SRC.read_text())
    open_segs, buried, route = [], [], []
    for seg in d["ditch"]["segments"]:
        target = buried if seg.get("buried") else open_segs
        pts = seg["points"]
        for a, b in zip(pts, pts[1:]):
            target.append([a[0], a[1], b[0], b[1]])
            route.append([a[0], a[1], b[0], b[1], 1 if seg.get("buried") else 0])
    spine = d["pond"]["spine_x_z_halfwidth_m"]
    cut = d["pond"]["cut_north_shore"]
    out_open, out_buried, out_route = [], [], []
    for seg in d["overflow"]["segments"]:
        target = out_buried if seg.get("buried") else out_open
        pts = seg["points"]
        for a, b in zip(pts, pts[1:]):
            target.append([a[0], a[1], b[0], b[1]])
            out_route.append([a[0], a[1], b[0], b[1], 1 if seg.get("buried") else 0])
    text = f"""extends RefCounted
## GENERATED by tools/build_water_data.py from {SRC.relative_to(ROOT)}: do not edit by hand (D-140).
## The ditch and pond as traced from the drone imagery, in scene metres
## (+x east, +z south). Read by terrain_math.gd to carve the ground.

## Metres. Ditch: depth, width at the top of the bank, width of the flat bottom.
const DITCH_DEPTH := {d["ditch"]["depth_m"]}
const DITCH_TOP_WIDTH := {d["ditch"]["width_m"]}
const DITCH_BOTTOM_WIDTH := {d["ditch"]["bottom_width_m"]}
## Pond: depth at the deepest, and the horizontal run of the bank from rim to floor.
const POND_DEPTH := {d["pond"]["depth_m"]}
const POND_BANK_RUN := {d["pond"]["bank_run_m"]}
## Where the water enters the ditch.
const WEIR := Vector2({d["weir"]["pos"][0]}, {d["weir"]["pos"][1]})

## Open ditch, one segment per four numbers: ax, az, bx, bz. These are carved.
static var DITCH_SEGMENTS := PackedFloat32Array([
{flat(open_segs)}
])

## Buried pipe and culvert runs, same layout. Not carved: they run under level ground.
static var PIPE_SEGMENTS := PackedFloat32Array([
{flat(buried)}
])

## The whole route from the weir to the pond in flow order, five numbers per
## segment: ax, az, bx, bz, buried (1) or open (0). The water simulation runs
## along this; the two lists above are the same segments split by kind.
static var ROUTE_SEGMENTS := PackedFloat32Array([
{flat(route)}
])

## Pond outline: x, z, half-width per spine point, drawn as a union of tapered circles.
static var POND_SPINE := PackedFloat32Array([
{flat(spine)}
])

## The pond's cut-back north shore (D-172), x, z per point from east to west: the
## pond is only the ground south of this line, between its first and last x.
static var POND_CUT := PackedFloat32Array([
{flat(cut)}
])

## The overflow (D-172): where a full pond spills, from the pond to the back of
## the property, in flow order, five numbers per segment (ax, az, bx, bz, buried).
static var OUTFLOW_SEGMENTS := PackedFloat32Array([
{flat(out_route)}
])

## The overflow's open runs (carved like the ditch) and buried culvert.
static var OUTFLOW_DITCH_SEGMENTS := PackedFloat32Array([
{flat(out_open)}
])
static var OUTFLOW_PIPE_SEGMENTS := PackedFloat32Array([
{flat(out_buried)}
])
"""
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(open_segs)} open ditch segments, {len(buried)} buried, {len(spine)} pond spine points, {len(cut)} shore points, {len(out_route)} overflow segments")


if __name__ == "__main__":
    main()
