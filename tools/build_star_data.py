#!/usr/bin/env python3
"""Builds project/scripts/star_data.gd: the bright stars and constellation lines
drawn by the night sky (D-104).

Source: the Yale Bright Star Catalogue, 5th revised edition (public domain),
as converted to JSON by Bretton Wade's YaleBrightStarCatalog (MIT):
https://github.com/brettonw/YaleBrightStarCatalog (bsc5-short.json).

    python3 tools/build_star_data.py path/to/bsc5-short.json

Keeps every star of visual magnitude <= MAG_LIMIT. Constellation lines are
listed below by constellation + Bayer letter and resolved against the
catalogue; the script fails if a name matches no star, so a typo can't silently
drop a line.
"""
import json
import re
import sys
from pathlib import Path

MAG_LIMIT = 5.0

# constellation abbreviation -> chains of Bayer letters, each chain drawn as a
# connected polyline. "UMa" = Ursa Major, etc.
CONSTELLATIONS = {
    "UMa": [["η", "ζ", "ε", "δ", "α", "β", "γ", "δ"]],               # Big Dipper
    "UMi": [["α", "δ", "ε", "ζ", "β", "γ", "η", "ζ"]],               # Little Dipper
    "Cas": [["β", "α", "γ", "δ", "ε"]],
    "Ori": [["λ", "α", "ζ", "ε", "δ", "γ", "λ"], ["ζ", "κ"], ["δ", "β"]],
    "Cyg": [["α", "γ", "β"], ["δ", "γ", "ε"]],                       # Northern Cross
    "Lyr": [["α", "ζ", "β", "γ", "δ", "ζ"]],
    "Aql": [["γ", "α", "β"]],
    "Leo": [["α", "η", "γ", "ζ", "μ", "ε"], ["γ", "δ", "β"], ["δ", "θ"]],
    "Peg": [["α", "β"]],                                             # Great Square: see EXTRA
    "And": [["α", "β", "γ"]],
    "Sco": [["β", "δ", "α"], ["δ", "π"]],
    "CrB": [["θ", "β", "α", "γ", "δ", "ε"]],
}
# Extra single segments between constellations, as ((con, letter), (con, letter)).
# The Great Square of Pegasus borrows Alpheratz (α And) as its fourth corner.
EXTRA = [(("Peg", "β"), ("And", "α")), (("And", "α"), ("Peg", "γ")), (("Peg", "γ"), ("Peg", "α"))]


def hms(s):
    h, m, sec = re.match(r"(\d+)h (\d+)m ([\d.]+)s", s).groups()
    return (int(h) + int(m) / 60 + float(sec) / 3600) * 15.0


def dms(s):
    sign = -1 if s.strip().startswith("-") else 1
    d, m, sec = re.match(r"[+-]?(\d+)° (\d+)′ ([\d.]+)″", s.strip()).groups()
    return sign * (int(d) + int(m) / 60 + float(sec) / 3600)


def main(path):
    raw = json.load(open(path))
    stars = []
    for s in raw:
        try:
            v = float(s["V"])
        except (KeyError, ValueError):
            continue
        stars.append({"ra": hms(s["RA"]), "dec": dms(s["Dec"]), "v": v,
                      "k": float(s.get("K", 6000) or 6000), "con": s.get("C"), "bayer": s.get("B"),
                      "name": s.get("N", "")})

    def find(con, letter):
        # "β¹" and "β²" both count as β; the brightest wins below.
        hits = [s for s in stars if s["con"] == con and (s["bayer"] or "").rstrip("¹²³⁴⁵⁶⁷⁸⁹") == letter]
        if not hits:
            sys.exit(f"no star for {letter} {con}")
        return min(hits, key=lambda s: s["v"])  # the brightest if a letter repeats

    segments = []
    for con, chains in CONSTELLATIONS.items():
        for chain in chains:
            pts = [find(con, l) for l in chain]
            for a, b in zip(pts, pts[1:]):
                segments.append((a, b))
    for (c1, l1), (c2, l2) in EXTRA:
        segments.append((find(c1, l1), find(c2, l2)))
    seen, unique = set(), []
    for a, b in segments:
        key = frozenset([(a["ra"], a["dec"]), (b["ra"], b["dec"])])
        if key not in seen:
            seen.add(key)
            unique.append((a, b))

    bright = sorted((s for s in stars if s["v"] <= MAG_LIMIT), key=lambda s: s["v"])
    out = ["extends RefCounted",
           "## GENERATED by tools/build_star_data.py: do not edit by hand (D-104).",
           "## Bright stars from the Yale Bright Star Catalogue (public domain), as",
           "## flat arrays: STARS is [ra_deg, dec_deg, magnitude, kelvin] per star and",
           "## LINES is [ra1, dec1, ra2, dec2] per constellation line segment (J2000).",
           "",
           "static var STARS := PackedFloat32Array([",
           ]
    for s in bright:
        out.append("\t%.3f, %.3f, %.2f, %d," % (s["ra"], s["dec"], s["v"], s["k"]))
    out += ["])", "", "static var LINES := PackedFloat32Array(["]
    for a, b in unique:
        out.append("\t%.3f, %.3f, %.3f, %.3f," % (a["ra"], a["dec"], b["ra"], b["dec"]))
    out += ["])", ""]
    dest = Path(__file__).resolve().parent.parent / "project" / "scripts" / "star_data.gd"
    dest.write_text("\n".join(out))
    print(f"{len(bright)} stars, {len(unique)} line segments -> {dest}")
    for con in CONSTELLATIONS:
        names = [find(con, l)["name"] or l for l in CONSTELLATIONS[con][0]]
        print(con, names)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
